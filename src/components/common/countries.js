// Merges the backend's country names into the static list (case-insensitive
// de-dupe, backend spelling wins so GET /countries/{name}/universities keeps
// matching what the server expects) and returns it sorted A-Z.
export const mergeCountries = (apiList = []) => {
  const byKey = new Map();
  ALL_COUNTRIES.forEach((c) => byKey.set(c.toLowerCase(), c));
  apiList.forEach((c) => {
    if (typeof c === 'string' && c.trim()) byKey.set(c.trim().toLowerCase(), c.trim());
  });
  return [...byKey.values()].sort((a, b) => a.localeCompare(b));
};
